import PDFDocument from 'pdfkit';

export interface InvoicePdfInput {
  number: string;
  tenantName: string;
  tenantNameAr?: string | null;
  country: string;
  currency: string;
  periodStart: Date;
  periodEnd: Date;
  dueDate: Date;
  subtotal: number;
  vatRate: number;
  vatAmount: number;
  total: number;
  lines: Array<{ description: string; quantity: number; unitPrice: number; lineTotal: number }>;
  notes?: string | null;
}

export function generateInvoicePdf(input: InvoicePdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margin: 50,
        info: { Title: `Invoice ${input.number}`, Author: 'LMMS' },
      });
      const chunks: Buffer[] = [];
      doc.on('data', (c: Buffer) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      doc.fontSize(20).fillColor('#0f172a').text('Invoice', { align: 'left' });
      doc.fontSize(12).fillColor('#334155').text(input.number);
      doc.moveDown();

      doc.fontSize(12).fillColor('#0f172a').text(input.tenantName);
      if (input.tenantNameAr) {
        doc.fontSize(10).fillColor('#64748b').text(input.tenantNameAr, { align: 'right' });
      }
      doc.fontSize(10).fillColor('#64748b').text(`Country: ${input.country}`);
      doc
        .fontSize(10)
        .fillColor('#64748b')
        .text(
          `Period: ${input.periodStart.toISOString().slice(0, 10)} → ${input.periodEnd.toISOString().slice(0, 10)}`,
        );
      doc
        .fontSize(10)
        .fillColor('#64748b')
        .text(`Due: ${input.dueDate.toISOString().slice(0, 10)}`);
      doc.moveDown();

      doc.fontSize(11).fillColor('#0f172a').text('Line items');
      doc.moveDown(0.5);

      for (const l of input.lines) {
        doc
          .fontSize(10)
          .fillColor('#334155')
          .text(`${l.description}`, { continued: true });
        doc
          .fillColor('#0f172a')
          .text(
            `  ${l.quantity} × ${l.unitPrice.toFixed(2)} = ${input.currency} ${l.lineTotal.toFixed(2)}`,
            { align: 'right' },
          );
      }

      doc.moveDown();
      doc
        .fontSize(10)
        .fillColor('#334155')
        .text(`Subtotal: ${input.currency} ${input.subtotal.toFixed(2)}`);
      doc.text(
        `VAT (${(input.vatRate * 100).toFixed(2)}%): ${input.currency} ${input.vatAmount.toFixed(2)}`,
      );
      doc
        .fontSize(12)
        .fillColor('#0f172a')
        .text(`Total: ${input.currency} ${input.total.toFixed(2)}`);

      if (input.notes) {
        doc.moveDown();
        doc.fontSize(9).fillColor('#64748b').text(input.notes);
      }

      doc.moveDown();
      doc.fontSize(8).fillColor('#94a3b8').text('Generated by LMMS. Confidential.');
      doc.end();
    } catch (e) {
      reject(e);
    }
  });
}
