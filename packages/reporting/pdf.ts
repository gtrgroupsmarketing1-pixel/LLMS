import PDFDocument from 'pdfkit';
import type { Kpis } from './metrics';
import type { Period } from './period';

export interface PdfInput {
  tenantNameEn: string;
  tenantNameAr: string;
  period: Period;
  kpis: Kpis;
  mode: 'ERP_CONNECTED' | 'STANDALONE' | 'UPGRADING';
}

function row(doc: PDFKit.PDFDocument, label: string, value: string): void {
  doc.fontSize(10).fillColor('#334155').text(label, { continued: true });
  doc.fillColor('#0f172a').text(`  ${value}`);
}

export function generateMonthlyPdf(input: PdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margin: 50,
        info: {
          Title: `${input.tenantNameEn} — Performance Report`,
          Author: 'LMMS',
        },
      });
      const chunks: Buffer[] = [];
      doc.on('data', (c: Buffer) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      doc.fontSize(18).fillColor('#0f172a').text('Performance Report');
      doc.fontSize(12).fillColor('#334155').text(input.tenantNameEn);
      doc.fontSize(10).fillColor('#64748b').text(input.tenantNameAr, { align: 'right' });
      doc.moveDown();
      doc
        .fontSize(10)
        .fillColor('#334155')
        .text(
          `Period: ${input.period.start.toISOString().slice(0, 10)} → ${input.period.end.toISOString().slice(0, 10)}`,
        );
      doc.text(`Mode: ${input.mode}`);
      doc.moveDown();

      const k = input.kpis;
      row(doc, 'Campaigns sent', String(k.campaignsSent));
      row(doc, 'Messages sent', String(k.messagesSent));
      row(doc, 'Delivery rate', `${(k.deliveryRate * 100).toFixed(1)}%`);
      row(doc, 'Read rate', `${(k.readRate * 100).toFixed(1)}%`);
      row(doc, 'Reply rate', `${(k.replyRate * 100).toFixed(1)}%`);
      row(doc, 'Failure rate', `${(k.failureRate * 100).toFixed(1)}%`);
      row(doc, 'Opt-out rate', `${(k.optOutRate * 100).toFixed(1)}%`);
      row(doc, 'Attributed revenue', String(k.attributedRevenue));
      if (input.mode === 'ERP_CONNECTED' || input.mode === 'UPGRADING') {
        row(doc, 'Attributed orders', String(k.attributedOrders));
        row(doc, 'Unattributed revenue', String(k.unattributedRevenue));
      }
      row(doc, 'Commercial contracts signed', String(k.commercialContractsSigned));
      row(doc, 'Reviews (new)', String(k.reviewsNew));
      row(doc, 'Average rating', k.averageRating === null ? '—' : k.averageRating.toFixed(2));
      row(doc, 'Review response rate', `${(k.reviewsRespondedRate * 100).toFixed(1)}%`);
      row(doc, 'GBP calls', String(k.gbpCalls));
      row(doc, 'GBP direction requests', String(k.gbpDirections));
      if (k.roas !== null) row(doc, 'ROAS', k.roas.toFixed(2));
      if (k.costPerAcquisition !== null) row(doc, 'CPA', k.costPerAcquisition.toFixed(2));

      doc.moveDown();
      doc.fontSize(8).fillColor('#94a3b8').text('Generated by LMMS. Confidential.');
      doc.end();
    } catch (e) {
      reject(e);
    }
  });
}
