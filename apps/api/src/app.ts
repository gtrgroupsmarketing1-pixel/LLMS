import express from 'express';
import { errorHandler } from './middleware/error';
import { requestIdMiddleware } from './middleware/requestId';
import { globalRateLimit } from './middleware/rateLimit';
import { tenantScopeGuard } from './middleware/tenantScope';
import { authRouter } from './routes/auth.routes';
import { tenantRouter } from './routes/tenant.routes';
import { ingestionRouter } from './routes/ingestion.routes';
import { segmentationRouter } from './routes/segmentation.routes';
import { campaignRouter } from './routes/campaign.routes';
import { complianceRouter } from './routes/compliance.routes';
import { automationRouter } from './routes/automation.routes';
import { portalRouter } from './routes/portal.routes';
import { reportingRouter } from './routes/reporting.routes';
import { contentCalendarRouter } from './routes/content-calendar.routes';
import { contentNotificationRouter } from './routes/content-notification.routes';
import { contentPortalV2Router } from './routes/content-portal-v2.routes';
import { migrationRouter } from './routes/migration.routes';
import { migrationPipelineRouter } from './routes/migration-pipeline.routes';
import { journeyRouter } from './routes/journey.routes';
import { brandRouter } from './routes/brand.routes';
import { reviewsRouter } from './routes/reviews.routes';
import { adsRouter } from './routes/ads.routes';
import { attributionRouter } from './routes/attribution.routes';
import { b2bRouter } from './routes/b2b.routes';
import { billingRouter } from './routes/billing.routes';
import { agencyRouter } from './routes/agency.routes';
import { qbrRouter } from './routes/qbr.routes';
import { websiteRouter } from './routes/website.routes';
import { pushRouter } from './routes/push.routes';
import { selfServeRouter } from './routes/self-serve.routes';
import { resellerRouter } from './routes/reseller.routes';
import { residencyRouter } from './routes/residency.routes';
import { marketplaceRouter } from './routes/marketplace.routes';
import { erpMigrationRouter } from './routes/erp-migration.routes';
import { modulesRouter } from './routes/modules.routes';

export function createApp() {
  const app = express();
  app.use(express.json({ limit: '10mb' }));
  app.use(requestIdMiddleware);
  app.use(globalRateLimit);

  app.get('/health', (_req, res) => res.json({ ok: true, service: 'lmms-api' }));

  app.use('/auth', authRouter);
  app.use('/tenants', tenantScopeGuard, tenantRouter);
  app.use('/ingestion', tenantScopeGuard, ingestionRouter);
  app.use('/segmentation', tenantScopeGuard, segmentationRouter);
  app.use('/campaigns', tenantScopeGuard, campaignRouter);
  app.use('/compliance', complianceRouter);
  app.use('/automations', tenantScopeGuard, automationRouter);
  app.use('/portal', portalRouter);
  app.use('/reporting', tenantScopeGuard, reportingRouter);
  app.use('/content-calendar', contentCalendarRouter);
  app.use('/content-notifications', contentNotificationRouter);
  app.use('/content-portal', contentPortalV2Router);
  app.use('/migration', tenantScopeGuard, migrationRouter);
  app.use('/migration-pipeline', migrationPipelineRouter);
  app.use('/journeys', tenantScopeGuard, journeyRouter);
  app.use('/brand', brandRouter);
  app.use('/reviews', reviewsRouter);
  app.use('/ads', tenantScopeGuard, adsRouter);
  app.use('/attribution', tenantScopeGuard, attributionRouter);
  app.use('/b2b', tenantScopeGuard, b2bRouter);
  app.use('/billing', billingRouter);
  app.use('/agency', agencyRouter);
  app.use('/qbr', tenantScopeGuard, qbrRouter);
  app.use('/website', websiteRouter);
  app.use('/push', pushRouter);
  app.use('/self-serve', selfServeRouter);
  app.use('/resellers', resellerRouter);
  app.use('/residency', residencyRouter);
  app.use('/marketplace', marketplaceRouter);
  app.use('/erp-migration', erpMigrationRouter);
  app.use('/modules', modulesRouter);

  app.use(errorHandler);
  return app;
}
